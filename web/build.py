#!/usr/bin/env python3
"""
espmui Asset Compiler & Bundler
Minifies, gzips, and packages web assets into a micro-sized binary bundle (< 16 KB).
"""

import gzip
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
HTML_PATH = os.path.join(HERE, "index.html")
DIST_DIR = os.path.join(HERE, "dist")
GZ_OUT_PATH = os.path.join(DIST_DIR, "web_assets.gz")
ASSETS_PY_PATH = os.path.join(HERE, "../src/espmui/assets.py")


def minify_html(raw: str) -> str:
    """Lightweight minifier for HTML, inline CSS, and JS."""
    # Remove HTML comments (except conditionals)
    text = re.sub(r"<!--(?!\[if).*?-->", "", raw, flags=re.DOTALL)
    # Collapse multiple whitespace outside of pre tags
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return "\n".join(lines)


def build():
    os.makedirs(DIST_DIR, exist_ok=True)

    with open(HTML_PATH, "r", encoding="utf-8") as f:
        raw_html = f.read()

    minified = minify_html(raw_html)
    raw_size = len(raw_html.encode("utf-8"))
    min_size = len(minified.encode("utf-8"))

    # Gzip compress with level 9
    gz_bytes = gzip.compress(minified.encode("utf-8"), compresslevel=9)
    gz_size = len(gz_bytes)

    # Save .gz file to dist
    with open(GZ_OUT_PATH, "wb") as f:
        f.write(gz_bytes)

    # Generate assets.py with frozen bytes literal
    assets_code = f'''"""
Compiled and pre-gzipped web assets for espmui.
Auto-generated by web/build.py.
Original: {raw_size:,} bytes | Minified: {min_size:,} bytes | Gzipped: {gz_size:,} bytes
"""

ASSET_BYTES = {repr(gz_bytes)}
IS_GZIP = True

def get_asset_payload():
    """Returns (data_bytes, is_gzip)."""
    return ASSET_BYTES, IS_GZIP
'''

    with open(ASSETS_PY_PATH, "w", encoding="utf-8") as f:
        f.write(assets_code)

    print("=" * 55)
    print(" espmui Asset Build Complete")
    print("=" * 55)
    print(f" Raw HTML:       {raw_size:>6} bytes")
    print(f" Minified HTML:  {min_size:>6} bytes")
    print(f" Gzipped Bundle: {gz_size:>6} bytes  ({(gz_size / raw_size) * 100:.1f}% of original)")
    print(f" Target:         {ASSETS_PY_PATH}")
    print("=" * 55)


if __name__ == "__main__":
    build()
